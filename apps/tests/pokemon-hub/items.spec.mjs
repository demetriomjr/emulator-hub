  await expect.poll(async () => (await itemOrder('ruby-a', 'items')).slots[0].quantity).toBe(beforeSource.slots[0].quantity - 2)
  const afterDestination = await itemOrder('sapphire-a', 'items')
  expect(afterDestination.slots[0].quantity).toBe(beforeDestination.slots[0].quantity + 2)
  expect(afterDestination.revision).toBe(beforeDestination.revision + 1)
