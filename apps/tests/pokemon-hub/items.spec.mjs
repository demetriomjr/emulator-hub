const audits = new WeakMap()
test.beforeEach(async ({ page }) => { audits.set(page, await watchSnapshots(page)) })
test.afterEach(async ({ page }, testInfo) => {
  try {
    if (await page.getByRole('dialog', { name: 'Pokémon Hub' }).isVisible()) await closeWorkspace(page)
  } finally { await audits.get(page)(testInfo) }
})

async function itemOrder(name, area) {
  const { bytes, revision } = await readItemSave(name)
  return { revision, slots: readPokemonItemInventory(bytes, itemProfiles[name].title).areas[area].slots }
}

async function dragAcross(page, from, destinationPane, areaLabel, destinationSlot = 0) {
  const start = await from.boundingBox()
  const panel = await pane(page, destinationPane).boundingBox()
  expect(start).not.toBeNull()
  expect(panel).not.toBeNull()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(start.x + start.width / 2 + 8, start.y + start.height / 2 + 8, { steps: 4 })
  await page.mouse.move(panel.x + panel.width / 2, panel.y + 150, { steps: 12 })
  await expect(pane(page, destinationPane).locator('.pokemon-item-area-nav h4')).toHaveText(areaLabel)
  const target = itemSlot(page, destinationPane, areaLabel, destinationSlot)
  const end = await target.boundingBox()
  expect(end).not.toBeNull()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 12 })
  await page.mouse.up()
}

function hubItemSlot(page, index, name, slot) {
  return pane(page, index).getByRole('listitem', { name: new RegExp(`^Itens de ${name}, posição ${slot + 1},`) })
}

