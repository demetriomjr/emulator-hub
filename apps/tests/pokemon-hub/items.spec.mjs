  const prompt = pane(page, 1).getByRole('dialog', { name: /Transferir Potion/ })
  const quantity = prompt.getByRole('spinbutton')
  const confirm = prompt.getByRole('button', { name: 'Transferir' })
  await expect(quantity).toHaveValue('1')
  await expect(prompt).toContainText('1 / 1')
  for (const invalid of ['0', '-1', '1.5', '2']) {
    await quantity.fill(invalid)
    await expect(confirm).toBeDisabled()
  }
  expect((await itemOrder('ruby-stack-capacity-source', 'items')).revision).toBe(initialSource.revision)
  expect((await itemOrder('emerald-stack-98', 'items')).revision).toBe(initialDestination.revision)
  await quantity.fill('1')
  await confirm.click()
  await expect.poll(async () => (await itemOrder('emerald-stack-98', 'items')).slots[0].quantity).toBe(99)
  const finalSource = await itemOrder('ruby-stack-capacity-source', 'items')
  const finalDestination = await itemOrder('emerald-stack-98', 'items')
  expect(finalSource.slots[0].quantity).toBe(initialSource.slots[0].quantity - 1)
  expect(finalDestination.revision).toBe(initialDestination.revision + 1)
  const fullSourceBytes = (await readItemSave('ruby-stack-capacity-source')).bytes
  const fullDestinationBytes = (await readItemSave('emerald-stack-98')).bytes
  await dragAcross(page, itemSlot(page, 0, 'Itens', 0), 1, 'Itens')
  await expect(pane(page, 1).getByRole('dialog', { name: /Transferir/ })).toHaveCount(0)
  expect((await itemOrder('ruby-stack-capacity-source', 'items')).revision).toBe(finalSource.revision)
  expect((await itemOrder('emerald-stack-98', 'items')).revision).toBe(finalDestination.revision)
  expect((await readItemSave('ruby-stack-capacity-source')).bytes).toEqual(fullSourceBytes)
  expect((await readItemSave('emerald-stack-98')).bytes).toEqual(fullDestinationBytes)
